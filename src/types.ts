/** All monetary amounts are INTEGER PAISE (1 rupee = 100 paise). Dates are 'YYYY-MM-DD' strings in the configured timezone. */

export type Paise = number
export type ISODate = string // YYYY-MM-DD
export type Timestamp = string // full ISO instant

interface Base {
  id: string
  createdAt: Timestamp
  updatedAt: Timestamp
  /** true for records loaded from the optional sample dataset */
  isSample?: boolean
}

export type AccountType = 'cash' | 'savings' | 'current' | 'upi' | 'other'
export const ACCOUNT_TYPES: { value: AccountType; label: string }[] = [
  { value: 'cash', label: 'Cash' },
  { value: 'savings', label: 'Savings bank account' },
  { value: 'current', label: 'Current account' },
  { value: 'upi', label: 'UPI / payment account' },
  { value: 'other', label: 'Other' },
]

export interface Account extends Base {
  name: string
  type: AccountType
  /** Balance before the first tracked transaction. Can be negative (e.g. overdraft). */
  openingBalance: Paise
  /** Optional manual reconciliation: what the bank actually shows on `asOf`. */
  actualBalance?: { amount: Paise; asOf: ISODate }
  archived?: boolean
}

export type TxType = 'income' | 'expense' | 'transfer'
export type PaymentMethod = 'cash' | 'upi' | 'card' | 'netbanking' | 'cheque' | 'auto-debit' | 'other'
export const PAYMENT_METHODS: { value: PaymentMethod; label: string }[] = [
  { value: 'upi', label: 'UPI' },
  { value: 'cash', label: 'Cash' },
  { value: 'card', label: 'Card' },
  { value: 'netbanking', label: 'Net banking' },
  { value: 'auto-debit', label: 'Auto-debit / NACH' },
  { value: 'cheque', label: 'Cheque' },
  { value: 'other', label: 'Other' },
]
export type Frequency = 'weekly' | 'monthly' | 'yearly'

export interface Transaction extends Base {
  type: TxType
  amount: Paise // always > 0
  date: ISODate
  accountId: string // source account (or the only account for income/expense)
  toAccountId?: string // transfers only
  categoryId?: string // income/expense only
  paymentMethod: PaymentMethod
  merchant?: string // payer for income, merchant for expense
  notes?: string
  essential?: boolean // expenses: essential vs discretionary
  recurring?: Frequency
  /** set when this expense was generated by a loan payment (keeps loan + ledger in sync without double counting) */
  loanPaymentId?: string
}

export interface Category extends Base {
  name: string
  kind: 'income' | 'expense'
  color: string
  /** default essential flag suggested for new expenses */
  essential?: boolean
  builtIn?: boolean
}

export interface Budget extends Base {
  categoryId: string
  month: string // YYYY-MM
  amount: Paise
}

export interface Loan extends Base {
  name: string
  lender: string
  principal: Paise // original
  outstanding: Paise // current outstanding principal (manually correctable)
  annualRate: number // percent, e.g. 8.5
  emi: Paise
  dueDay: number // 1..31 (clamped to month length)
  startDate: ISODate
  tenureMonths: number
  endDate?: ISODate // expected end date
  accountId?: string // default account EMIs are paid from
  /** editable repayment plan */
  extraMonthly?: Paise
  notes?: string
}

export interface LoanPayment extends Base {
  loanId: string
  date: ISODate
  kind: 'emi' | 'prepayment'
  amount: Paise // total paid
  interest: Paise
  principal: Paise
  accountId?: string
  transactionId?: string
  notes?: string
}

export type GoalKind = 'emergency' | 'savings' | 'debt-free' | 'purchase' | 'custom'
export const GOAL_KINDS: { value: GoalKind; label: string }[] = [
  { value: 'emergency', label: 'Emergency fund' },
  { value: 'savings', label: 'Savings target' },
  { value: 'debt-free', label: 'Debt-free target' },
  { value: 'purchase', label: 'Major purchase' },
  { value: 'custom', label: 'Custom goal' },
]

export interface Goal extends Base {
  name: string
  kind: GoalKind
  target: Paise
  /** Earmarked amount. This is NOT additional money: it is part of an account's balance. Ignored for debt-free goals (derived from loans). */
  saved: Paise
  targetDate?: ISODate
  /** the account in which the earmarked money physically sits */
  accountId?: string
  notes?: string
}

export interface Settings {
  id: 'app'
  currency: 'INR'
  timezone: string
  theme: 'light' | 'dark'
  lastBackupAt?: Timestamp
  backupReminderDays: number
  sampleLoaded?: boolean
  dismissedBackupBannerAt?: Timestamp
}

export interface DateRange {
  from: ISODate
  to: ISODate
}
